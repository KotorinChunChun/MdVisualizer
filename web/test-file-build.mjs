const crc32 = (bytes) => { let value = 0xffffffff; for (const byte of bytes) { value ^= byte; for (let bit = 0; bit < 8; bit += 1) value = (value >>> 1) ^ (value & 1 ? 0xedb88320 : 0); } return (value ^ 0xffffffff) >>> 0; };
const chunk = (kind, bytes) => { const type = Buffer.from(kind); const output = Buffer.alloc(12 + bytes.length); output.writeUInt32BE(bytes.length, 0); type.copy(output, 4); Buffer.from(bytes).copy(output, 8); output.writeUInt32BE(crc32(Buffer.concat([type, Buffer.from(bytes)])), 8 + bytes.length); return output; };
